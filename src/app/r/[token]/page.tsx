import { createClient } from "@/lib/supabase/server";
import { notFound } from "next/navigation";
import { formatDate } from "@/lib/utils";

export default async function SharedReportPage({ params }: { params: Promise<{ token: string }> }) {
  const { token } = await params;
  const supabase = await createClient();

  const { data: report } = await supabase
    .from("ai_reports")
    .select("*, children(name, grade)")
    .eq("shared_token", token)
    .single();

  if (!report) notFound();

  const child = report.children as { name: string; grade: string | null } | null;

  return (
    <div className="min-h-screen bg-surface-muted p-6">
      <div className="max-w-2xl mx-auto">
        {/* Header */}
        <div className="flex items-center gap-3 mb-8">
          <div className="w-10 h-10 rounded-2xl bg-brand-gradient flex items-center justify-center text-xl">🌱</div>
          <span className="font-bold text-xl text-ink">GrowthOS Kids</span>
        </div>

        <div className="card p-8">
          <div className="flex items-start justify-between mb-6">
            <div>
              <h1 className="text-2xl font-bold text-ink capitalize">
                {report.report_type} Growth Report
              </h1>
              {child && (
                <p className="text-ink-muted mt-1">
                  {child.name}{child.grade ? ` · ${child.grade}` : ""}
                </p>
              )}
              <p className="text-sm text-ink-subtle mt-0.5">
                {formatDate(report.period_start)} – {formatDate(report.period_end)}
              </p>
            </div>
            <div className="badge-brand">{report.report_type}</div>
          </div>

          {report.summary && (
            <div className="bg-brand-50 border border-brand-100 rounded-2xl p-5 mb-6">
              <p className="text-ink leading-relaxed whitespace-pre-line">{report.summary}</p>
            </div>
          )}

          {(report.recommendations as string[])?.length > 0 && (
            <div className="mt-6">
              <h2 className="font-bold text-ink mb-3">Recommendations</h2>
              <div className="space-y-3">
                {(report.recommendations as string[]).map((rec, i) => (
                  <div key={i} className="flex items-start gap-3 p-3 rounded-xl bg-surface-subtle">
                    <div className="w-6 h-6 rounded-full bg-brand-500 text-white flex items-center justify-center text-xs font-bold shrink-0">
                      {i + 1}
                    </div>
                    <p className="text-sm text-ink">{rec}</p>
                  </div>
                ))}
              </div>
            </div>
          )}

          <div className="mt-8 pt-6 border-t border-surface-border text-center">
            <p className="text-xs text-ink-subtle">
              Generated by GrowthOS Kids AI · {formatDate(report.generated_at, "MMM d, yyyy 'at' h:mm a")}
            </p>
            <a href="/" className="text-xs text-brand-500 hover:underline mt-1 block">
              Track your child's growth at growthos.kids
            </a>
          </div>
        </div>
      </div>
    </div>
  );
}
